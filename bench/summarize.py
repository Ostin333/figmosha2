#!/usr/bin/env python3

import json
import statistics
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
FIELDS = ("input_tokens", "output_tokens", "calls", "errors", "seconds", "manual_fixes")


def load(runs_dir):
    runs = []
    for path in sorted(runs_dir.glob("*.json")):
        try:
            run = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as e:
            raise SystemExit(f"{path.name}: {e}")
        for key in ("tool", "scenario"):
            if not isinstance(run.get(key), str):
                raise SystemExit(f"{path.name}: missing '{key}'")
        runs.append(run)
    return runs


def median(values):
    nums = [v for v in values if isinstance(v, (int, float)) and not isinstance(v, bool)]
    return statistics.median(nums) if nums else None


def fmt(value):
    if value is None:
        return "—"
    return f"{value:,.0f}" if value >= 100 else f"{value:g}"


def summarize(runs):
    groups = defaultdict(list)
    for run in runs:
        groups[(run["scenario"], run["tool"])].append(run)
    lines = [
        "# Benchmark results",
        "",
        "Medians over runs. Generated by `bench/summarize.py` — do not edit by hand.",
        "",
        "| Scenario | Tool | Runs | Passed | Input tokens | Output tokens | Calls | Errors | Seconds | Manual fixes |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for (scenario, tool), group in sorted(groups.items()):
        passed = sum(1 for r in group if r.get("passed") is True)
        cells = [fmt(median([r.get(f) for r in group])) for f in FIELDS]
        lines.append(f"| {scenario} | {tool} | {len(group)} | {passed}/{len(group)} | "
                     + " | ".join(cells) + " |")
    if not groups:
        lines.append("| — | no runs recorded yet | | | | | | | | |")
    return "\n".join(lines) + "\n"


def main(argv):
    runs_dir = Path(argv[1]) if len(argv) > 1 else HERE / "runs"
    out = HERE / "RESULTS.md"
    out.write_text(summarize(load(runs_dir)), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main(sys.argv)
